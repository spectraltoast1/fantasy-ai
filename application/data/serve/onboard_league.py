def assert_in_scope(lid: str, summary: dict) -> None:
    """V1 is redraft only (CODING_BIBLE §4) — decline out-of-scope shapes, never mis-handle them.

    Sleeper's `settings.type` is 0/1/2 = redraft/keeper/dynasty. **Absence is not redraft**: the
    corpus recovery found 7 known keeper/dynasty leagues with the key missing, so an unknown type
    refuses too. The other two V1 constraints police themselves — an unscoreable custom scoring
    profile yields a `cust-*` key with no `projection_consensus`, which the substrate assertion
    already raises on, and 1QB/superflex are both in scope.

    This is the loud stop, not the product's answer. S5 owns the graceful user-facing rejection.

    **The lifecycle rule is THE SAME FUNCTION the API greys the button with** (P5/S4d):
    `platforms.league_has_started`. It is authoritative *here* rather than there, because
    `platforms.classify` is advisory by its own docstring and `POST /api/connect` runs no
    classification at all on a pasted league id — so the worker is the only place that has to be
    right. It costs no extra Sleeper call: `status` is already on the `summary` dict the caller
    fetched one line above. P5/S4f swaps this refusal for a `pending` hold, reusing the predicate.
    """
    t = summary.get("league_type")
    if t != "redraft":
        raise SystemExit(
            f"league {lid} is {t or 'of unknown type'} (Sleeper settings.type={summary.get('raw_type')!r}) "
            f"— V1 supports REDRAFT only.\n"
            "  Absence of the key is NOT treated as redraft: known keeper/dynasty leagues omit it, "
            "and guessing here would mis-score somebody's season.")

    started, why = platforms.league_has_started(summary)
    if not started:
        raise SystemExit(
            f"{why}, so this league has no rosters yet and there is nothing to build from.\n"
            "  Nothing is wrong with the league or with your account. Link it again once your "
            "draft is done and the season is under way.")


def onboard(lid: str, season: int, *, to_week: int | None = None, do_load: bool = True,
            dry_run: bool = False, stage=_print_stage) -> dict:
    """Onboard one league end to end: chain → catalog row → load that COMMITS.

    The order is load-bearing. The catalog parquet is written BEFORE the load because
    `build_db.load_league` resolves its slices from `_catalog()` — the league has to be catalogued
    for the loader to agree it exists. The Postgres catalog row then goes in inside the load's own
    transaction (`catalog=True`), so discoverability and readability commit together.

    `stage` is the same observer `run_chain` already took, now threaded through the whole entry
    point (P5/S4b) — including the two steps that were outside it, the preflight and the load. The
    worker passes one that writes the job's state into Postgres, so the states a reader sees come
    from THE chain rather than from a second description of it that could drift. `bench_cold_league`
    still calls `run_chain` directly with its timing observer; nothing about it changes.
    """
    lid = str(lid)
    report: dict = {"league_id": lid, "season": season, "to_week": to_week, "stages": {}}

    # Everything that decides whether this league may be onboarded at all, inside one stage. S5 adds
    # its preflight here; today it is coldness, scope and the season match. Every refusal in this
    # block is deterministic — retrying cannot change the answer — which is what makes it the
    # `rejected` boundary for the queue.
    with stage("validating"):
        state = classify(lid, season)
        report["state"] = state
        print(f"onboarding {lid} ({season}) — state: {state.upper()}")

        summary = sleeper.league_summary(lid)
        assert_in_scope(lid, summary)
        if summary.get("season") is not None and int(summary["season"]) != int(season):
            raise SystemExit(f"league {lid} is Sleeper season {summary['season']}, not {season}. "
                             "A Sleeper league_id belongs to exactly one season.")
        lineage_id, how = resolve_lineage_root(lid, summary)
        report["lineage_id"], report["lineage_rule"] = lineage_id, how
        print(f"  name={summary.get('name')!r}  teams={summary.get('total_rosters')}  "
              f"type={summary.get('league_type')}\n  lineage_id={lineage_id} ({how})")

    run_chain(lid, season, to_week=to_week, report=report, stage=stage)
    row = build_catalog_row(lid, season, report["scoring_key"], summary, lineage_id)
    report["catalog_row"] = row.row(0, named=True)
    print("\n--- catalog row ---")
    for k, v in report["catalog_row"].items():
        print(f"  {k:20s} {v!r}")

    if dry_run:
        print("\n--dry-run: nothing catalogued, nothing loaded.")
        return report

    # The catalog write and the Postgres load are ONE stage, because they are one commitment: the
    # parquet row is what makes `load_league` agree the league exists, and the Postgres catalog row
    # goes in inside the load's own transaction. A crash between them is the resumable window that
    # `classify` returns `resume` for.
    with stage("loading"):
        dl.write_connected_league(row, lid, season)
        print(f"✓ connected_catalog.parquet now holds {dl.read_connected_catalog().height} row(s)")

        if do_load:
            with psycopg.connect(database_url()) as conn:
                counts = build_db.load_league(conn, lid, catalog=True)
            report["load"] = counts
            total = sum(v for k, v in counts.items() if k != "league_catalog")
            print(f"✓ COMMITTED {total} rows across "
                  f"{len([k for k in counts if k != 'league_catalog'])} "
                  f"table(s) + {counts.get('league_catalog', 0)} catalog row; every other league untouched")
            for ds in build_db.DATASETS:
                if counts.get(ds.table):
                    print(f"    {ds.table:22s} {counts[ds.table]:>6d} rows")
        else:
            print("--no-load: the derived store and the catalog parquet are written; Postgres is not.")
    return report


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--league", required=True, help="the Sleeper league_id to onboard")
    ap.add_argument("--season", type=int, required=True)
    ap.add_argument("--to-week", type=int, default=None,
                    help="cap join+spine at this week (models an early-season connect)")
    ap.add_argument("--no-load", action="store_true", help="build + catalog, but do not write Postgres")
    ap.add_argument("--dry-run", action="store_true",
                    help="run the chain and print the catalog row; write neither it nor Postgres")
    a = ap.parse_args()
    onboard(a.league, a.season, to_week=a.to_week, do_load=not a.no_load, dry_run=a.dry_run)


if __name__ == "__main__":
    main()
